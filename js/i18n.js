const SUPPORTED_LANGS = ["fr", "en", "es"];
const LANG_LABELS = { fr: "Français", en: "English", es: "Español" };

function getCurrentLang(){
  const stored = localStorage.getItem("ebl_lang");
  if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
  const nav = (navigator.language || "fr").slice(0,2);
  return SUPPORTED_LANGS.includes(nav) ? nav : "fr";
}

function t(key){
  const lang = getCurrentLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.fr[key] || key;
}

function applyTranslations(){
  const lang = getCurrentLang();
  document.documentElement.setAttribute("lang", lang);
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (el.hasAttribute("data-i18n-attr")) {
      el.setAttribute(el.getAttribute("data-i18n-attr"), val);
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  const titleKey = document.documentElement.getAttribute("data-title-key");
  if (titleKey) document.title = t(titleKey);
  const descTag = document.querySelector('meta[name="description"]');
  if (descTag && descTag.getAttribute("data-i18n")) descTag.setAttribute("content", t(descTag.getAttribute("data-i18n")));
  document.querySelectorAll(".lang-current [data-lang-label]").forEach(el => { el.textContent = LANG_LABELS[lang]; });
  document.querySelectorAll("[data-lang-option]").forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("data-lang-option") === lang);
  });
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

function setLang(lang){
  if (!SUPPORTED_LANGS.includes(lang)) return;
  localStorage.setItem("ebl_lang", lang);
  applyTranslations();
}

document.addEventListener("DOMContentLoaded", applyTranslations);
